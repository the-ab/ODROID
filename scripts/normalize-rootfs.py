"""Remove host workspace ACLs from an offline image root, preserving file capabilities."""
from pathlib import Path
import argparse,os,subprocess
if not __debug__:raise SystemExit('Run without Python optimization: validation must remain enabled')

def normalize(root):
    root=root.resolve()
    assert os.geteuid()==0 and root.name in ('rootfs-minimized','rootfs-minimal')
    assert (root.parent/'.odroid-workspace').is_file() and (root/'etc/os-release').is_file()
    assert not any(os.path.ismount(root/name) for name in ['proc','sys','dev','run']),'Run outside the chroot mount namespace'
    subprocess.run(['setfacl','-R','-b','-k',str(root)],check=True)
    os.chown(root,0,0);root.chmod(0o755)
    for name in ['etc/systemd/system','etc/ssh/sshd_config.d','usr/local/bin','usr/local/sbin','usr/share/odroid-u3','usr/share/doc/odroid-u3-firmware']:
        path=root/name
        if path.is_dir():os.chown(path,0,0);path.chmod(0o755)
    # These files are generated by the recipe, rather than unpacked with dpkg modes.
    for name in ['etc/sysctl.d/10-apparmor.conf','etc/hostname','etc/hosts','etc/timezone','etc/locale.gen','etc/default/locale','etc/default/odroid-fan','etc/machine-id','etc/fstab','etc/odroid-image-release','etc/apt/sources.list.d/ubuntu.sources','etc/ssh/sshd_config.d/10-image-access.conf','usr/share/odroid-u3/fan-layout.json']:
        p=root/name
        if p.is_file() and not p.is_symlink():os.chown(p,0,0);p.chmod(0o644)
    for path in (root/'etc/systemd/system').rglob('*'):
        if path.is_symlink():continue
        if path.is_dir():path.chmod(0o755)
        elif path.is_file():path.chmod(0o644)
    for name in ['usr/local/sbin/odroid-fan','usr/local/sbin/odroid-network-identity','usr/local/sbin/odroid-grow-root','usr/local/bin/odroid-gpu']:
        path=root/name
        if path.exists():os.chown(path,0,0);path.chmod(0o755)
    print('Offline image root normalized; host ACLs removed, capabilities retained')
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,required=True);normalize(p.parse_args().root)
